"""Generate ABAP class ZCL_ISU_MOCK_LOADER that inserts the mock IS-U data
into the Z tables on the BTP ABAP environment (run it with F9 in ADT)."""
from __future__ import annotations

import json
import sqlite3
from collections import defaultdict

from . import config

OUT = config.ROOT / "abap" / "classes" / "zcl_isu_mock_loader.clas.abap"
CHUNK = 150  # rows per INSERT statement keeps each statement small

DATE_COLS = {"einzdat", "auszdat", "ab", "bis", "adat", "abrdats", "abrdate", "created_on"}


def _lit(col, val):
    if val is None or val == "":
        return "' '" if col not in DATE_COLS else "'00000000'"
    if col in DATE_COLS:
        return "'" + str(val).replace("-", "") + "'"
    s = str(val).replace("'", "''")
    return f"'{s}'"


def export(n_accounts: int = 16) -> str:
    truth = json.loads(config.GROUND_TRUTH_PATH.read_text())
    per = defaultdict(list)
    for g in truth:
        per[g["scenario"]].append(g["vkont"])
    picked = []
    while len(picked) < n_accounts and any(per.values()):
        for sc in list(per):
            if per[sc] and len(picked) < n_accounts:
                picked.append(per[sc].pop(0))

    con = sqlite3.connect(config.DB_PATH)
    con.row_factory = sqlite3.Row
    q = ",".join("?" * len(picked))
    sel = {
        "zisu_fkkvkp": f"SELECT * FROM fkkvkp WHERE vkont IN ({q})",
        "zisu_but000": f"SELECT b.* FROM but000 b JOIN fkkvkp k ON k.partner=b.partner WHERE k.vkont IN ({q})",
        "zisu_ever": f"SELECT * FROM ever WHERE vkont IN ({q})",
        "zisu_eanl": f"SELECT a.* FROM eanl a JOIN ever v ON v.anlage=a.anlage WHERE v.vkont IN ({q})",
        "zisu_egerh": f"SELECT g.* FROM egerh g JOIN ever v ON v.anlage=g.anlage WHERE v.vkont IN ({q})",
        "zisu_eabl": f"SELECT r.* FROM eabl r JOIN egerh g ON g.equnr=r.equnr JOIN ever v ON v.anlage=g.anlage WHERE v.vkont IN ({q})",
        "zisu_erch": f"SELECT e.* FROM erch e JOIN ever v ON v.vertrag=e.vertrag WHERE v.vkont IN ({q})",
        "zisu_dberchz": f"SELECT d.*, 'EUR' AS waers FROM dberchz d JOIN erch e ON e.belnr=d.belnr JOIN ever v ON v.vertrag=e.vertrag WHERE v.vkont IN ({q})",
        "zisu_rates": "SELECT * FROM rates",
    }
    body = []
    total = 0
    for tab, sql in sel.items():
        rows = [dict(r) for r in con.execute(sql, picked if "?" in sql else ())]
        total += len(rows)
        body.append(f"    DELETE FROM {tab}.")
        for start in range(0, len(rows), CHUNK):
            chunk = rows[start:start + CHUNK]
            lines = ["      ( " + " ".join(f"{c} = {_lit(c, v)}" for c, v in r.items()) + " )" for r in chunk]
            body.append(f"    INSERT {tab} FROM TABLE @( VALUE #(\n" + "\n".join(lines) + "\n    ) ).")
        body.append(f"    out->write( |{tab}: {len(rows)} rows| ).\n")

    abap = f'''"! Loads synthetic IS-U data for the Bill Anomaly Explainer POC.
"! Generated by: python -m isu_agent.cli export-abap  ({len(picked)} accounts, {total} rows)
"! Run in ADT with F9 (Run as Console Application).
CLASS zcl_isu_mock_loader DEFINITION PUBLIC FINAL CREATE PUBLIC.
  PUBLIC SECTION.
    INTERFACES if_oo_adt_classrun.
ENDCLASS.

CLASS zcl_isu_mock_loader IMPLEMENTATION.
  METHOD if_oo_adt_classrun~main.
{chr(10).join(body)}
    COMMIT WORK.
    out->write( |Done. Accounts: {", ".join(picked)}| ).
  ENDMETHOD.
ENDCLASS.
'''
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(abap)
    return f"Wrote {OUT} ({len(picked)} accounts, {total} rows)"
